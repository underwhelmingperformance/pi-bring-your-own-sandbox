import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

import ts from 'typescript';

import manifest from '../packages/sdk/package.json' with { type: 'json' };

const sdk = path.resolve(import.meta.dirname, '../packages/sdk');
const distribution = path.join(sdk, 'dist');
const report = path.join(sdk, 'api-report.txt');
const entryPoints = Object.entries(manifest.publishConfig.exports);
const program = ts.createProgram(
	entryPoints.map(([, entry]) => path.join(sdk, entry.types)),
	{
		module: ts.ModuleKind.NodeNext,
		moduleResolution: ts.ModuleResolutionKind.NodeNext,
		skipLibCheck: true,
		strict: true
	}
);
const checker = program.getTypeChecker();
const printer = ts.createPrinter({
	newLine: ts.NewLineKind.LineFeed,
	removeComments: true
});

function resolveAlias(symbol: ts.Symbol): ts.Symbol {
	return (symbol.flags & ts.SymbolFlags.Alias) === 0
		? symbol
		: checker.getAliasedSymbol(symbol);
}

const declarations = new Map<ts.Declaration, string>();

function collect(symbol: ts.Symbol): void {
	const targets = resolveAlias(symbol).declarations ?? [];

	for (const declaration of targets) {
		const file = declaration.getSourceFile();
		const location = path.relative(distribution, file.fileName);

		if (
			ts.isTypeParameterDeclaration(declaration) ||
			location.startsWith('..' + path.sep) ||
			path.isAbsolute(location) ||
			declarations.has(declaration)
		) {
			continue;
		}

		declarations.set(declaration, location.replaceAll(path.sep, '/'));
		visit(declaration);
	}
}

function compareText(left: string, right: string): number {
	return Number(left > right) - Number(left < right);
}

function visit(node: ts.Node): void {
	let reference: ts.Node | undefined;

	if (ts.isTypeReferenceNode(node)) {
		reference = node.typeName;
	}

	if (ts.isTypeQueryNode(node)) {
		reference = node.exprName;
	}

	if (
		ts.isExpressionWithTypeArguments(node) ||
		ts.isComputedPropertyName(node)
	) {
		reference = node.expression;
	}

	if (ts.isImportTypeNode(node)) {
		reference = node.qualifier;
	}

	if (reference !== undefined) {
		const symbol = checker.getSymbolAtLocation(reference);

		if (symbol !== undefined) {
			collect(symbol);
		}
	}

	ts.forEachChild(node, visit);
}

function entryPoint([subpath, entry]: (typeof entryPoints)[number]): string {
	const file = program.getSourceFile(path.join(sdk, entry.types));
	const entryModule =
		file === undefined ? undefined : checker.getSymbolAtLocation(file);

	if (entryModule === undefined) {
		throw new Error(
			'Missing built declarations for ' + subpath + '. Run pnpm build.'
		);
	}

	const exports = checker.getExportsOfModule(entryModule).map((symbol) => {
		const target = resolveAlias(symbol);
		const [declaration] = target.declarations ?? [];

		if (declaration === undefined) {
			throw new Error('Cannot resolve ' + symbol.name + ' in ' + subpath);
		}

		collect(target);

		const kind =
			symbol.declarations?.some(
				(alias) =>
					ts.isExportSpecifier(alias) &&
					(alias.isTypeOnly || alias.parent.parent.isTypeOnly)
			) === true || (target.flags & ts.SymbolFlags.Value) === 0
				? 'type'
				: 'value';
		const name =
			symbol.name === target.name
				? symbol.name
				: target.name + ' as ' + symbol.name;
		const location = path
			.relative(distribution, declaration.getSourceFile().fileName)
			.replaceAll(path.sep, '/');

		return kind + ' ' + name + ' (' + location + ')';
	});

	return [
		manifest.name + subpath.slice(1),
		...exports.toSorted(compareText)
	].join('\n');
}

const entries = entryPoints
	.toSorted(([left], [right]) => compareText(left, right))
	.map((entry) => entryPoint(entry));
const signatureBlocks = [...declarations]
	.map(([declaration, location]) => {
		const signature = printer.printNode(
			ts.EmitHint.Unspecified,
			declaration,
			declaration.getSourceFile()
		);

		return (
			'// ' +
			location +
			'\n' +
			(ts.isVariableDeclaration(declaration)
				? 'declare const ' + signature + ';'
				: signature)
		);
	})
	.toSorted(compareText);
const fresh =
	[
		'Generated by pnpm api:report.',
		...entries,
		'Declarations referenced by the public entry points\n\n' +
			signatureBlocks.join('\n\n')
	].join('\n\n') + '\n';

if (process.argv.includes('--write')) {
	await writeFile(report, fresh);
} else if ((await readFile(report, 'utf8')) !== fresh) {
	process.stderr.write(
		'The SDK API report differs from the build. Run pnpm api:report.\n'
	);
	process.exitCode = 1;
}
